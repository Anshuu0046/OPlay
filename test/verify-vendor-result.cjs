const {execFileSync}=require('node:child_process');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const file=path.resolve(__dirname,'../../../outputs/Aether-calibration-verification.json');
const report=JSON.parse(fs.readFileSync(file,'utf8'));
const logFile=path.join(process.env.LOCALAPPDATA,'NVIDIA Corporation/NVIDIA App/CxNative_NVIDIA App.log');
const lines=fs.readFileSync(logFile,'utf8').trim().split(/\r?\n/).slice(-256);
const last=pattern=>lines.filter(line=>pattern.test(line)).at(-1);
const completionLine=last(/completionStatus : \d+/),stableLine=last(/stable : \d+/),offsetLine=last(/averageGpuClockOffsetMhz : -?\d+/);
assert.ok(completionLine&&stableLine&&offsetLine,'Native persisted scanner result required');
const completionStatus=Number(completionLine.match(/completionStatus : (\d+)/)[1]);
const stable=Number(stableLine.match(/stable : (\d+)/)[1]);
const offset=Number(offsetLine.match(/averageGpuClockOffsetMhz : (-?\d+)/)[1]);
assert.ok(completionStatus&4,'NVIDIA completedSuccessfully bit required');assert.equal(stable,1);
const output=execFileSync('powershell.exe',['-NoProfile','-File',path.resolve(__dirname,'../src/worker.ps1'),'-SkipNvml'],{input:JSON.stringify({id:1,action:'vendorScan',mode:'Read'})+'\n',windowsHide:true,encoding:'utf8'});
const response=JSON.parse(output.trim());assert.equal(response.ok,true);const state=response.data;
assert.equal(state.running,false);assert.equal(state.available,true);assert.ok(state.message.includes('GPU Tuning: +'+offset+' MHz'));
assert.ok(/Updated \d+ minutes? ago/.test(state.message),'Recent persisted result required');
assert.ok(!/interrupt|fail|cancel|days? ago/i.test(state.message));
report.observationNote=report.error;delete report.error;
report.passed=true;report.finish=state;report.resultVerifiedAt=new Date().toISOString();
report.persistedResult={completionStatus,stable,averageGpuClockOffsetMHz:offset,evidence:[completionLine,stableLine,offsetLine]};
report.scope='Successful persisted NVIDIA scanner result corroborated by native completion flag, stable flag, and recent Performance panel value. Observer coverage ended before completion; no game FPS comparison or CPU/system-RAM overclock validation.';
fs.writeFileSync(file,JSON.stringify(report,null,2));console.log('PASS: persisted NVIDIA scanner success and stable flag match recent +'+offset+' MHz Performance panel result.');
